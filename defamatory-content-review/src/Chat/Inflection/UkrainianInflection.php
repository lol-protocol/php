<?php

namespace DefamatoryContentReview\Chat\Inflection;

/** Declinación regular del ucraniano: sustantivos, adjetivos en -ий/-ій y verbos en -ати. Ver SuffixInflection. */
final class UkrainianInflection extends SuffixInflection
{
    protected function nouns(): array
    {
        return [
            '/^(.+)ець$/u' => ['ець', 'ця', 'цю', 'цем', 'цеві', 'ці', 'ців', 'цям', 'цями', 'цях'], // мерзотець → мерзотця
            '/^(.+)ень$/u' => ['ень', 'ня', 'ню', 'нем', 'неві', 'ні', 'нів', 'ням', 'нями', 'нях'], // дурень → дурня
            '/^(.+)ок$/u' => ['ок', 'ка', 'ку', 'ком', 'кові', 'ки', 'ків', 'кам', 'ками', 'ках'],
            '/^(.+[гкх])$/u' => ['а', 'у', 'ом', 'ові', 'е', 'и', 'ів', 'ам', 'ами', 'ах'],
            '/^(.+[жшчщ])$/u' => ['а', 'у', 'ем', 'еві', 'е', 'і', 'ів', 'ам', 'ами', 'ах'],
            '/^(.+[бвдзлмнпрстфц])$/u' => ['а', 'у', 'ом', 'ові', 'е', 'и', 'ів', 'ам', 'ами', 'ах'],
            '/^(.+)[йь]$/u' => ['я', 'ю', 'ем', 'єм', 'еві', 'і', 'ів', 'їв', 'ей', 'ям', 'ями', 'ях'],
            '/^(.+)ка$/u' => ['ки', 'ці', 'ку', 'кою', 'ко', 'кам', 'ками', 'ках', 'ок'],
            '/^(.+)га$/u' => ['ги', 'зі', 'гу', 'гою', 'го', 'гам', 'гами', 'гах', 'г'],
            '/^(.+)а$/u' => ['и', 'і', 'у', 'ою', 'о', 'ам', 'ами', 'ах', ''],
            '/^(.+)я$/u' => ['і', 'ї', 'ю', 'єю', 'є', 'ям', 'ями', 'ях', 'ь'],
            '/^(.+)о$/u' => ['а', 'у', 'ом', 'ові', 'ам', 'ами', 'ах', ''],
            '/^(.+)е$/u' => ['я', 'ю', 'ем', 'ям', 'ями', 'ях', 'ь'],
        ];
    }

    protected function adjectives(): array
    {
        return [
            '/^(.+)ий$/u' => ['ий', 'ого', 'ому', 'им', 'ім', 'ої', 'ій', 'у', 'ою', 'а', 'е', 'і', 'их', 'ими'],
            '/^(.+)ій$/u' => ['ій', 'ього', 'ьому', 'ім', 'ьої', 'ю', 'я', 'є', 'і', 'іх', 'іми'],
        ];
    }

    protected function verb(string $lemma): array
    {
        if (preg_match('/^(.+а)ти$/u', $lemma, $m) !== 1) {
            return [$lemma];
        }

        return array_map(fn(string $ending): string => $m[1] . $ending, ['ти', 'ю', 'єш', 'є', 'ємо', 'єте', 'ють', 'в', 'ла', 'ло', 'ли', 'й', 'йте']);
    }
}
