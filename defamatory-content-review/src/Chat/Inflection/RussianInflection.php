<?php

namespace DefamatoryContentReview\Chat\Inflection;

/**
 * Declinación regular del ruso: los casos del singular y del plural de los
 * sustantivos masculinos, femeninos y neutros, y los adjetivos en -ый/-ой/-ий;
 * los verbos en -ать/-ять. Ver SuffixInflection.
 */
final class RussianInflection extends SuffixInflection
{
    protected function nouns(): array
    {
        return [
            '/^(.+)ец$/u' => ['ец', 'ца', 'цу', 'цем', 'це', 'цы', 'цев', 'цам', 'цами', 'цах', 'еца', 'ецу', 'ецом', 'еце', 'ецы', 'ецов', 'ецам', 'ецами', 'ецах'], // мерзавец → мерзавца, подлец → подлеца
            '/^(.+)ёл$/u' => ['ёл', 'ла', 'лу', 'лом', 'ле', 'лы', 'лов', 'лам', 'лами', 'лах'], // козёл → козла
            '/^(.+)ень$/u' => ['ень', 'ня', 'ню', 'нем', 'не', 'ни', 'ней', 'ням', 'нями', 'нях'], // пень → пня
            '/^(.+)ок$/u' => ['ок', 'ка', 'ку', 'ком', 'ке', 'ки', 'ков', 'кам', 'ками', 'ках'], // щенок → щенка
            '/^(.+[гкх])$/u' => ['а', 'у', 'ом', 'е', 'и', 'ов', 'ам', 'ами', 'ах'],
            '/^(.+[жшчщ])$/u' => ['а', 'у', 'ем', 'ом', 'е', 'и', 'ей', 'ам', 'ами', 'ах'],
            '/^(.+ц)$/u' => ['а', 'у', 'ем', 'ом', 'е', 'ы', 'ев', 'ов', 'ам', 'ами', 'ах'],
            '/^(.+[бвдзлмнпрстф])$/u' => ['а', 'у', 'ом', 'е', 'ы', 'ов', 'ам', 'ами', 'ах'],
            '/^(.+)[йь]$/u' => ['я', 'ю', 'ем', 'е', 'и', 'ев', 'ей', 'ям', 'ями', 'ях', 'ью'],
            '/^(.+[гкхжшчщ])а$/u' => ['и', 'е', 'у', 'ой', 'ей', 'ам', 'ами', 'ах', ''],
            '/^(.+)а$/u' => ['ы', 'е', 'у', 'ой', 'ою', 'ам', 'ами', 'ах', ''],
            '/^(.+)я$/u' => ['и', 'е', 'ю', 'ей', 'ею', 'ям', 'ями', 'ях', 'ь'],
            '/^(.+)о$/u' => ['а', 'у', 'ом', 'е', 'ам', 'ами', 'ах', ''],
            '/^(.+)е$/u' => ['я', 'ю', 'ем', 'ям', 'ями', 'ях', 'ей'],
        ];
    }

    protected function adjectives(): array
    {
        return [
            '/^(.+[гкх])ий$/u' => ['ий', 'ого', 'ому', 'им', 'ом', 'ая', 'ой', 'ую', 'ое', 'ие', 'их', 'ими'],
            '/^(.+[жшчщ])ий$/u' => ['ий', 'его', 'ого', 'ему', 'ому', 'им', 'ем', 'ом', 'ая', 'ей', 'ую', 'ое', 'ие', 'их', 'ими'],
            '/^(.+)ий$/u' => ['ий', 'его', 'ему', 'им', 'ем', 'яя', 'ей', 'юю', 'ее', 'ие', 'их', 'ими'],
            '/^(.+)ый$/u' => ['ый', 'ого', 'ому', 'ым', 'ом', 'ая', 'ой', 'ую', 'ою', 'ое', 'ые', 'ых', 'ыми'],
            '/^(.+)ой$/u' => ['ой', 'ого', 'ому', 'ым', 'ом', 'ая', 'ую', 'ою', 'ое', 'ые', 'ых', 'ыми'],
        ];
    }

    protected function verb(string $lemma): array
    {
        if (preg_match('/^(.+)ова(ть)$/u', $lemma, $m) === 1) { // насиловать → насилую, насиловал
            $base = $m[1];

            return array_merge([$lemma], array_map(fn(string $e): string => $base . $e, ['ую', 'уешь', 'ует', 'уем', 'уете', 'уют', 'овал', 'овала', 'овало', 'овали', 'уй']));
        }
        if (preg_match('/^(.+[ая])ть$/u', $lemma, $m) !== 1) {
            return [$lemma];
        }

        return array_map(fn(string $ending): string => $m[1] . $ending, ['ть', 'ю', 'ешь', 'ет', 'ем', 'ете', 'ют', 'л', 'ла', 'ло', 'ли', 'й', 'йте']);
    }
}
