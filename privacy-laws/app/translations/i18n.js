let currentLang = "eng";

export async function loadTranslations(lang = "eng") {
  if (!translations[lang]) {
    console.warn(`Language ${lang} not found, defaulting to eng`);
    currentLang = "eng";
  } else {
    currentLang = lang;
  }
  updateUIText();
}

export function t(key) {
  return translations[currentLang]?.[key] || translations.eng[key] || key;
}

export function getCurrentLanguage() {
  return currentLang;
}

export function getAvailableLanguages() {
  return Object.keys(translations);
}

function updateUIText() {
  // Update HTML attributes for language
  document.documentElement.lang = currentLang;
  // Dispatch event so UI components can update
  document.dispatchEvent(new CustomEvent("languageChanged", { detail: { lang: currentLang } }));
}
